// --- Kua calculation ---
function sumDigits(n: number): number {
  let s = n
  while (s >= 10) {
    s = String(s).split("").reduce((acc, d) => acc + Number(d), 0)
  }
  return s
}

export interface KuaResult {
  kuaNumber: number   // effective kua (5 replaced)
  rawKua: number      // original kua (may be 5)
  displayKua: string  // e.g. "3" or "(5) 8"
  group: "east" | "west"
}

export function calculateKua(birthDateStr: string, gender: Gender): KuaResult {
  const date = new Date(birthDateStr)
  let year = date.getFullYear()
  const month = date.getMonth() + 1 // 1-based
  const day = date.getDate()

  // Chinese New Year cutoff: Jan 1 – Feb 4 inclusive → use previous year
  if (month === 1 || (month === 2 && day <= 4)) {
    year -= 1
  }

  // Use last two digits of the year, then reduce to single digit
  const lastTwo = year % 100
  const S = sumDigits(lastTwo)

  let kua: number
  if (gender === "male") {
    kua = year < 2000 ? 10 - S : 9 - S
    if (kua <= 0) kua += 9
  } else {
    kua = year < 2000 ? S + 5 : S + 6
    kua = sumDigits(kua)
  }

  const rawKua = kua
  let effective = kua

  // Special case: Kua 5 doesn't exist in 8 Mansions
  if (kua === 5) {
    effective = gender === "male" ? 2 : 8
  }

  const displayKua = String(kua)
  const eastGroup = [1, 3, 4, 9]
  const group: "east" | "west" = eastGroup.includes(effective) ? "east" : "west"

  return { kuaNumber: effective, rawKua, displayKua, group }
}

